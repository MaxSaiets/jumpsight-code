"""Repository statistics: lines by language, lines per package, test counts.

    python tools/repo_stats.py            # print
    python tools/repo_stats.py --write    # also write docs/STATISTICS.generated.md

Every number is counted from the files on disk (and from `pytest --collect-only`);
nothing is typed in by hand. Generated and vendored directories are skipped.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_DIRS = {
    ".git",
    "__pycache__",
    "node_modules",
    "var",
    "venv",
    ".venv",
    ".pytest_cache",
    ".ruff_cache",
    "models",
    "data",
    "dist",
    "build",
}
LANGUAGES = {
    ".py": "Python",
    ".js": "JavaScript",
    ".cjs": "JavaScript",
    ".mjs": "JavaScript",
    ".html": "HTML",
    ".css": "CSS",
    ".md": "Markdown",
    ".json": "JSON",
    ".yaml": "YAML",
    ".yml": "YAML",
    ".toml": "TOML",
    ".sh": "Shell",
    ".ps1": "PowerShell",
    ".cmd": "Batch",
}


def _files():
    for path in sorted(ROOT.rglob("*")):
        if path.is_file() and not (set(path.relative_to(ROOT).parts[:-1]) & SKIP_DIRS):
            yield path


def _line_count(path: Path) -> int:
    try:
        with path.open("rb") as fh:
            return sum(1 for _ in fh)
    except OSError:
        return 0


def _package(path: Path) -> str:
    parts = path.relative_to(ROOT).parts
    if len(parts) == 1:
        return "(root)"
    if parts[0] in ("src", "tests", "experiments") and len(parts) > 2:
        return "/".join(parts[:2])
    return parts[0]


def collect() -> dict:
    by_lang: Counter = Counter()
    by_package: Counter = Counter()
    files_by_lang: Counter = Counter()
    for path in _files():
        lang = LANGUAGES.get(path.suffix.lower())
        if lang is None:
            continue
        n = _line_count(path)
        by_lang[lang] += n
        files_by_lang[lang] += 1
        by_package[_package(path)] += n
    test_files = (
        [
            p
            for p in (ROOT / "tests").rglob("*")
            if p.is_file()
            and (re.match(r"test_.*\.py$", p.name) or p.name.endswith(".test.js"))
            and "__pycache__" not in p.parts
        ]
        if (ROOT / "tests").is_dir()
        else []
    )
    return {"by_lang": by_lang, "files_by_lang": files_by_lang, "by_package": by_package, "test_files": len(test_files)}


def collect_tests() -> str:
    """Return the pytest collection summary line, or why it could not be collected."""
    cp = subprocess.run(
        [
            sys.executable,
            "-m",
            "pytest",
            "--collect-only",
            "-q",
            "-p",
            "no:cacheprovider",
            "-p",
            "no:warnings",
            "--continue-on-collection-errors",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    lines = [ln for ln in (cp.stdout or "").splitlines() if ln.strip()]
    summary = next((ln for ln in reversed(lines) if re.search(r"\d+ tests? collected", ln)), None)
    errors = [ln for ln in lines if "ERROR collecting" in ln]
    per_file = [int(m.group(1)) for ln in lines if (m := re.match(r"^\S+\.py: (\d+)$", ln.strip()))]
    ids = [ln for ln in lines if "::" in ln and not ln.startswith(("ERROR", "E "))]
    if summary:
        return summary.strip() + (f"; {len(errors)} collection errors" if errors else "")
    return f"{sum(per_file) or len(ids)} tests collected; {len(errors)} files failed to collect (exit {cp.returncode})"


def render(stats: dict, tests: str) -> str:
    out = [
        "# Repository statistics",
        "",
        "Generated by `python tools/repo_stats.py --write`; do not edit by hand.",
        "",
        "## Lines by language",
        "",
        "| Language | Files | Lines |",
        "|---|---:|---:|",
    ]
    for lang, n in stats["by_lang"].most_common():
        out.append(f"| {lang} | {stats['files_by_lang'][lang]} | {n} |")
    out.append(f"| **Total** | {sum(stats['files_by_lang'].values())} | {sum(stats['by_lang'].values())} |")
    out += ["", "## Lines by package", "", "| Package | Lines |", "|---|---:|"]
    for pkg, n in sorted(stats["by_package"].items()):
        out.append(f"| `{pkg}` | {n} |")
    out += ["", "## Tests", "", f"- test files: {stats['test_files']}", f"- `pytest --collect-only -q`: {tests}", ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="write docs/STATISTICS.generated.md")
    ap.add_argument("--no-collect", action="store_true", help="skip the pytest collection step")
    a = ap.parse_args()
    text = render(collect(), "not collected (--no-collect)" if a.no_collect else collect_tests())
    print(text)
    if a.write:
        target = ROOT / "docs" / "STATISTICS.generated.md"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        print(f"written: {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
