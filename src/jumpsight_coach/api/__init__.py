"""Coach API (mounted at /coach by the web app): recommendations, today's session, plans, goals,
history, accounts, verdict feedback, chat.

    python -m jumpsight_coach.api            # http://127.0.0.1:8100

POST /recommend  {result: <analysis result JSON>}
   -> {verdict, diagnosis[], why[], drills[], program{title,days[]}, cautions[],
       confidence, sources[], meta{kb_version, pipeline}}

Recommendations are deterministic (P9 + P8, no LLM). The chat (/ask) is the only LLM user, and it
validates the LLM output against retrieved sources.

Routes live in the area modules below; this package re-exports every name that tests and the web
app import, and mirrors assignments on the package into the modules that use them.
"""

